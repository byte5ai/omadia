/**
 * #2353 / ADR-0320 — the AI-disclosure line is written in the language of the
 * answer it is appended to; the operator's `ai_disclosure_locale` decides only
 * when the answer shows no clear German or English. Orchestrator from SOURCE.
 */
import { describe, it } from 'node:test';
import { strict as assert } from 'node:assert';

import type { LlmProvider, LlmResponse, LlmStreamEvent } from '@omadia/llm-provider';
import { InMemoryNudgeRegistry } from '@omadia/plugin-api';
import type { EntityRefBus, KnowledgeGraph, MemoryStore } from '@omadia/plugin-api';

import { detectAnswerLocale } from '../packages/harness-orchestrator/src/answerLanguage.js';
import {
  buildOrchestratorForAgent,
  type OrchestratorDeps,
} from '../packages/harness-orchestrator/src/buildOrchestrator.js';
import { NativeToolRegistry } from '../packages/harness-orchestrator/src/nativeToolRegistry.js';

const EN_LINE = 'This response was generated by an AI system.';
const DE_LINE = 'Diese Antwort wurde von einem KI-System erzeugt.';

const ENGLISH = 'There are three open invoices. The oldest one is from March and it is overdue.';
const GERMAN = 'Es gibt drei offene Rechnungen. Die älteste ist aus dem März und sie ist überfällig.';

function fixedProvider(text: string): LlmProvider {
  const response = {
    content: [{ type: 'text', text }],
    finishReason: 'stop',
    providerFinishReason: 'end_turn',
    model: 'test',
    usage: { inputTokens: 1, outputTokens: 1, cacheReadTokens: 0, cacheWriteTokens: 0 },
  } as unknown as LlmResponse;
  return {
    id: 'anthropic',
    capabilities: {
      tools: true,
      vision: true,
      streaming: true,
      promptCaching: true,
      forcedToolChoice: true,
      parallelToolCalls: true,
    },
    complete: async (): Promise<LlmResponse> => response,
    stream: (): AsyncIterable<LlmStreamEvent> => ({
      async *[Symbol.asyncIterator]() {
        yield { type: 'text_delta', text };
        yield { type: 'final', response };
      },
    }),
    classifyError: () => ({ retryable: false, kind: 'other' as const }),
  } as unknown as LlmProvider;
}

function orchestratorAnswering(text: string, locale?: 'de' | 'en') {
  const deps: OrchestratorDeps = {
    provider: fixedProvider(text),
    knowledgeGraph: undefined as unknown as KnowledgeGraph,
    memoryStore: undefined as unknown as MemoryStore,
    entityRefBus: undefined as unknown as EntityRefBus,
    nativeToolRegistry: new NativeToolRegistry(),
    nudgeRegistry: new InMemoryNudgeRegistry(),
    responseGuard: () => undefined,
    privacyGuard: () => undefined,
    ...(locale ? { aiDisclosure: { level: 'standard' as const, locale } } : {}),
  };
  return buildOrchestratorForAgent(
    { agentId: 'solo', model: 'test', maxTokens: 1024, maxToolIterations: 3 },
    deps,
  ).orchestrator;
}

describe('detectAnswerLocale (#2353)', () => {
  it('tells English and German prose apart', () => {
    assert.equal(detectAnswerLocale(ENGLISH), 'en');
    assert.equal(detectAnswerLocale(GERMAN), 'de');
  });

  it('is undecided for data, names and too little text', () => {
    assert.equal(detectAnswerLocale(undefined), undefined);
    assert.equal(detectAnswerLocale(''), undefined);
    assert.equal(detectAnswerLocale('42'), undefined);
    assert.equal(detectAnswerLocale('Anna Schmidt'), undefined);
    assert.equal(detectAnswerLocale('| Nr | Betrag |\n|---|---|\n| 1 | 20 € |'), undefined);
  });

  it('ignores code, links and markup', () => {
    const text =
      'Hier ist der Link, den du brauchst: https://example.com/the/and/of/to/is ' +
      '```\nconst theValueIsAndOf = this.or.that;\n```';
    assert.equal(detectAnswerLocale(text), 'de');
  });

  it('is undecided for a text that mixes both evenly', () => {
    assert.equal(detectAnswerLocale('the and of und der die'), undefined);
  });
});

describe('the disclosure line follows the answer language (#2353, ADR-0320)', () => {
  it('an English answer gets the English line (buffered)', async () => {
    const result = await orchestratorAnswering(ENGLISH).chat({ userMessage: 'Open invoices?' });
    assert.ok(result.text.endsWith(EN_LINE), result.text);
    assert.equal(result.aiDisclosure?.locale, 'en');
  });

  it('an English answer gets the English line (streaming)', async () => {
    let done: { answer: string; aiDisclosure?: { locale: string } } | undefined;
    for await (const ev of orchestratorAnswering(ENGLISH).chatStream({
      userMessage: 'Open invoices?',
    })) {
      if (ev.type === 'done') done = ev;
    }
    assert.ok(done, 'no done event');
    assert.ok(done.answer.endsWith(EN_LINE), done.answer);
    assert.equal(done.aiDisclosure?.locale, 'en');
  });

  it('the answer language wins over the operator locale', async () => {
    const result = await orchestratorAnswering(GERMAN, 'en').chat({ userMessage: 'Rechnungen?' });
    assert.ok(result.text.endsWith(DE_LINE), result.text);
  });

  it('an undecided answer keeps the operator locale, else German', async () => {
    const en = await orchestratorAnswering('42', 'en').chat({ userMessage: 'Wie viele?' });
    assert.ok(en.text.endsWith(EN_LINE), en.text);
    const de = await orchestratorAnswering('42').chat({ userMessage: 'How many?' });
    assert.ok(de.text.endsWith(DE_LINE), de.text);
  });
});

describe('an undecided answer follows the user message (#2367, ADR-0331)', () => {
  const SHORT_EN = "It's 4:42 PM (Europe/Berlin) on Friday, November 27, 2026.";

  it('decides a short text that shows only one language', () => {
    assert.equal(detectAnswerLocale(SHORT_EN), 'en');
    assert.equal(detectAnswerLocale('Es ist 16:42 Uhr.'), undefined);
    assert.equal(detectAnswerLocale('Wie spät ist es?'), 'de');
    assert.equal(detectAnswerLocale('Anna Schmidt'), undefined);
    // Single letters are labels as often as words (review of #2367).
    assert.equal(detectAnswerLocale('Raum A, Gebäude A'), undefined);
    assert.equal(detectAnswerLocale('Klasse I, Typ A'), undefined);
  });

  it('the short English routine answer gets the English line', async () => {
    const result = await orchestratorAnswering(SHORT_EN).chat({ userMessage: 'Tell me the time.' });
    assert.ok(result.text.endsWith(EN_LINE), result.text);
  });

  it('an undecided answer takes the language of the user message before the operator locale', async () => {
    const en = await orchestratorAnswering('42').chat({ userMessage: 'How many are there?' });
    assert.ok(en.text.endsWith(EN_LINE), en.text);
    const de = await orchestratorAnswering('42', 'en').chat({ userMessage: 'Wie viele gibt es?' });
    assert.ok(de.text.endsWith(DE_LINE), de.text);
  });

  it('the answer language still wins over the user message', async () => {
    const result = await orchestratorAnswering(GERMAN).chat({ userMessage: 'How many are there?' });
    assert.ok(result.text.endsWith(DE_LINE), result.text);
  });
});
