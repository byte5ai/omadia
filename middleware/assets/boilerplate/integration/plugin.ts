export const PLUGIN_ID = '{{AGENT_ID}}' as const;

/**
 * Capability plugin of kind `integration` (spec 2042 §5.10, ADR-0014).
 *
 * Runtime contract (tool runtime):
 *   - activate(ctx) has a 10s budget (self-test: 1 GET, no full crawl).
 *   - close()       has a 5s budget — REALLY release timers/connections/watches.
 *   - Every toolkit tool is registered via `ctx.tools.register` (see
 *     `registerTools.ts`). The kernel offers the tools to the agents the
 *     operator granted this plugin to; the calling agent decides when to
 *     use them. The plugin has no persona, no system prompt and no model
 *     loop of its own.
 */
export interface PluginHandle {
  close(): Promise<void>;
}

export async function activate(ctx: PluginContext): Promise<PluginHandle> {
  ctx.log('activating');

  // #region builder:activate-body
  // Secrets: resolved along the depends_on chain. `require` throws when missing.
  const apiToken = await ctx.secrets.require('API_TOKEN');

  // Config: non-secret setup.fields. `get<T>` for optional + default, `require<T>` for mandatory.
  const baseUrl = ctx.config.require<string>('base_url');
  const timeoutMs = ctx.config.get<number>('request_timeout_ms') ?? 15_000;

  const client = createClient({
    baseUrl,
    token: apiToken,
    timeoutMs,
    log: ctx.log,
  });

  // Self-test: lightweight, one GET. NOT a full crawl / bulk sync.
  await client.ping();
  ctx.log('self-test ok', { baseUrl });

  const toolkit: Toolkit = createToolkit({
    client,
    log: ctx.log,
  });
  // #endregion

  // #region builder:external-reads-init
  // Auto-generated from spec.external_reads — do not edit by hand. Codegen
  // synthesises typed `ctx.services.get(...)` lookups + tool descriptors
  // here from the declarative spec.external_reads[] entries; the LLM does
  // NOT fill this slot. Empty by default — the marker stays in place even
  // when the spec has no external reads.
  // #endregion

  // Every toolkit tool (including the external-reads tools pushed above)
  // goes to the kernel's tool runtime.
  const disposeTools = registerToolkit(ctx, toolkit);

  const __uiRouteDisposers: Array<() => void> = [];
  // #region builder:ui-routes-init
  // Auto-generated from spec.ui_routes — do not edit by hand. Codegen
  // synthesises per-route Express routers, `ctx.routes.register(...)`
  // mounts, and `ctx.uiRoutes.register(...)` descriptor wiring here.
  // The disposer-array above collects every register() return value so
  // close() can tear down everything cleanly. Empty by default.
  // #endregion

  return {
    async close() {
      ctx.log('deactivating');
      // B.12 — tear down every ui_route mount + descriptor. The loop is
      // always present (no-op when ui_routes is empty); the disposers are
      // pushed by the codegen-managed ui-routes-init region above.
      for (const dispose of __uiRouteDisposers) {
        try {
          dispose();
        } catch (err) {
          ctx.log('ui-route dispose failed', err);
        }
      }
      disposeTools();
      await toolkit.close();
    },
  };
}

export default { PLUGIN_ID, activate };
